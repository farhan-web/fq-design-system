/**
 * scripts/apply-tokens.mjs
 *
 * Reads design-reference/colors.json + spacing.json (output of scrape-screenshots.mjs)
 * and updates src/foundations/colors.css + spacing.css with the Passport palette.
 *
 * Usage:
 *   node scripts/apply-tokens.mjs
 *
 * Run AFTER: node scripts/scrape-screenshots.mjs
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const REF = path.join(ROOT, 'design-reference');
const FOUNDATIONS = path.join(ROOT, 'src', 'foundations');

// ─── Load scraped data ────────────────────────────────────────────────────────

function load(filename) {
  const p = path.join(REF, filename);
  if (!fs.existsSync(p)) {
    console.error(`Missing ${filename}. Run the scraper first:\n  node scripts/scrape-screenshots.mjs`);
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(p, 'utf-8'));
}

// ─── Color CSS generator ──────────────────────────────────────────────────────

function buildColorsCss(colors) {
  // Map Passport token names → semantic fq- token names
  const neutral = {
    '--color-neutral-0':   colors['N0']   ?? '#FFFFFF',
    '--color-neutral-100': colors['N100'] ?? '#F4F7FE',
    '--color-neutral-200': colors['N200'] ?? '#D8DCE8',
    '--color-neutral-400': colors['N400'] ?? '#AEB2BE',
    '--color-neutral-600': colors['N600'] ?? '#71747D',
    '--color-neutral-700': colors['N700'] ?? '#4D4F56',
    '--color-neutral-800': colors['N800'] ?? '#303135',
  };

  const blue = {
    '--color-blue-100': colors['B100'] ?? '#E7F2FF',
    '--color-blue-200': colors['B200'] ?? '#A3CFFF',
    '--color-blue-300': colors['B300'] ?? '#5BAAFF',
    '--color-blue-400': colors['B400'] ?? '#007CFF',
  };

  const green = {
    '--color-green-100': colors['G100'] ?? '#E2FBED',
    '--color-green-500': colors['G500'] ?? '#0BAE54',
  };

  const yellow = {
    '--color-yellow-100': colors['Y100'] ?? '#FEF8D0',
  };

  const red = {
    '--color-red-100': colors['R100'] ?? '#FFDFDF',
    '--color-red-400': colors['R400'] ?? '#F15C59',
  };

  // Semantic aliases — mapped to raw palette above
  const semantic = {
    // Brand / interactive
    '--color-primary':             'var(--color-blue-400)',
    '--color-primary-hover':       'var(--color-blue-300)',
    '--color-primary-subtle':      'var(--color-blue-100)',

    // Feedback
    '--color-success':             'var(--color-green-500)',
    '--color-success-subtle':      'var(--color-green-100)',
    '--color-warning':             'var(--color-yellow-100)',
    '--color-danger':              'var(--color-red-400)',
    '--color-danger-subtle':       'var(--color-red-100)',

    // Text
    '--color-text-high':           'var(--color-neutral-800)',
    '--color-text-medium':         'var(--color-neutral-700)',
    '--color-text-low':            'var(--color-neutral-600)',
    '--color-text-disabled':       'var(--color-neutral-400)',
    '--color-text-inverse':        'var(--color-neutral-0)',
    '--color-text-activity':       'var(--color-blue-400)',
    '--color-text-alert':          'var(--color-red-400)',

    // Surface / background
    '--color-background':          'var(--color-neutral-0)',
    '--color-surface':             'var(--color-neutral-100)',
    '--color-surface-raised':      'var(--color-neutral-0)',

    // Border
    '--color-border':              'var(--color-neutral-200)',
    '--color-border-strong':       'var(--color-neutral-400)',

    // Focus rings (keep existing)
    '--color-focus-ring':          'rgb(0 124 255 / 15%)',
    '--color-error-ring':          'rgb(241 92 89 / 15%)',
  };

  const toVars = (obj) =>
    Object.entries(obj).map(([k, v]) => `  ${k}: ${v};`).join('\n');

  return `/* src/foundations/colors.css
 * Passport Design System color tokens
 * Source: tiket.design/system/foundation/color-solid
 * Auto-generated by scripts/apply-tokens.mjs — do not edit raw values manually.
 */

:root {
  /* ── Neutral ──────────────────────────── */
${toVars(neutral)}

  /* ── Blue (Brand) ─────────────────────── */
${toVars(blue)}

  /* ── Green ────────────────────────────── */
${toVars(green)}

  /* ── Yellow ───────────────────────────── */
${toVars(yellow)}

  /* ── Red ──────────────────────────────── */
${toVars(red)}

  /* ── Semantic aliases ─────────────────── */
${toVars(semantic)}
}

/* Dark mode — explicit attribute */
[data-theme="dark"] {
  --color-primary:           var(--color-blue-300);
  --color-primary-hover:     var(--color-blue-400);
  --color-primary-subtle:    color-mix(in srgb, var(--color-blue-400) 15%, transparent);

  --color-text-high:         var(--color-neutral-0);
  --color-text-medium:       var(--color-neutral-200);
  --color-text-low:          var(--color-neutral-400);
  --color-text-disabled:     var(--color-neutral-600);
  --color-text-inverse:      var(--color-neutral-800);

  --color-background:        #0f172a;
  --color-surface:           #1e293b;
  --color-surface-raised:    #334155;

  --color-border:            #334155;
  --color-border-strong:     var(--color-neutral-600);

  --color-focus-ring:        rgb(91 170 255 / 20%);
  --color-error-ring:        rgb(241 92 89 / 20%);
}

/* Dark mode — system preference */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    --color-primary:           var(--color-blue-300);
    --color-primary-hover:     var(--color-blue-400);
    --color-primary-subtle:    color-mix(in srgb, var(--color-blue-400) 15%, transparent);

    --color-text-high:         var(--color-neutral-0);
    --color-text-medium:       var(--color-neutral-200);
    --color-text-low:          var(--color-neutral-400);
    --color-text-disabled:     var(--color-neutral-600);
    --color-text-inverse:      var(--color-neutral-800);

    --color-background:        #0f172a;
    --color-surface:           #1e293b;
    --color-surface-raised:    #334155;

    --color-border:            #334155;
    --color-border-strong:     var(--color-neutral-600);

    --color-focus-ring:        rgb(91 170 255 / 20%);
    --color-error-ring:        rgb(241 92 89 / 20%);
  }
}
`;
}

// ─── Spacing CSS generator ────────────────────────────────────────────────────

function buildSpacingCss(spacingData) {
  // Passport scale: 8, 12, 16, 24, 32, 48, 64, 96, 128
  // Fall back to this if scraper didn't capture it
  const scale = spacingData?.length
    ? spacingData
    : [
        { name: 'xs',    px: 4  },
        { name: 'sm',    px: 8  },
        { name: 'md',    px: 12 },
        { name: 'lg',    px: 16 },
        { name: 'xl',    px: 24 },
        { name: '2xl',   px: 32 },
        { name: '3xl',   px: 48 },
        { name: '4xl',   px: 64 },
        { name: '5xl',   px: 96 },
        { name: '6xl',   px: 128 },
      ];

  const vars = [4, 8, 12, 16, 24, 32, 48, 64, 96, 128]
    .map(px => `  --spacing-${px}: ${px}px;`)
    .join('\n');

  return `/* src/foundations/spacing.css
 * Spacing scale — mirrors Passport Design System layout scale
 * Auto-generated by scripts/apply-tokens.mjs
 */

:root {
${vars}

  /* Semantic aliases */
  --spacing-xs:  var(--spacing-4);
  --spacing-sm:  var(--spacing-8);
  --spacing-md:  var(--spacing-12);
  --spacing-lg:  var(--spacing-16);
  --spacing-xl:  var(--spacing-24);
  --spacing-2xl: var(--spacing-32);
  --spacing-3xl: var(--spacing-48);
  --spacing-4xl: var(--spacing-64);
}
`;
}

// ─── Main ─────────────────────────────────────────────────────────────────────

function main() {
  console.log('Reading scraped data...');
  const colors = load('colors.json');
  const spacing = fs.existsSync(path.join(REF, 'spacing.json'))
    ? JSON.parse(fs.readFileSync(path.join(REF, 'spacing.json'), 'utf-8'))
    : [];

  console.log(`  Colors : ${Object.keys(colors).length} tokens`);
  console.log(`  Spacing: ${spacing.length} entries`);

  const colorsCss = buildColorsCss(colors);
  const spacingCss = buildSpacingCss(spacing);

  const colorsDest = path.join(FOUNDATIONS, 'colors.css');
  const spacingDest = path.join(FOUNDATIONS, 'spacing.css');

  fs.writeFileSync(colorsDest, colorsCss);
  console.log(`\nWrote ${colorsDest}`);

  fs.writeFileSync(spacingDest, spacingCss);
  console.log(`Wrote ${spacingDest}`);

  console.log('\nDone! Run `npm run storybook` to preview the updated tokens.');
}

main();
